static float fp16_to_fp32(uint16_t h) {
    uint32_t sign = ((uint32_t)(h & 0x8000)) << 16;
    int exp = (h >> 10) & 0x1F;
    uint32_t mant = h & 0x3FF;
    uint32_t f;
    if (exp == 0) {
        if (mant == 0) {
            f = sign;
        } else {
            exp = 1;
            while (!(mant & 0x400)) { mant <<= 1; exp--; }
            mant &= 0x3FF;
            f = sign | ((uint32_t)(exp + 112) << 23) | (mant << 13);
        }
    } else if (exp == 31) {
        f = sign | 0x7F800000 | (mant << 13);
    } else {
        f = sign | ((uint32_t)(exp + 112) << 23) | (mant << 13);
    }
    float out;
    memcpy(&out, &f, sizeof(out));
    return out;
}

static void dequantize_row_q8_0(const block_q8_0 * x, float * y, int64_t k) {
    static const int qk = QK8_0;
    assert(k % qk == 0);
    const int nb = (int)(k / qk);
    for (int i = 0; i < nb; i++) {
        const float d = fp16_to_fp32(x[i].d);
        for (int j = 0; j < qk; ++j) {
            y[i*qk + j] = x[i].qs[j]*d;
        }
    }
}

static void dequantize_row_iq2_xxs(const block_iq2_xxs * x, float * y, int64_t k) {
    assert(k % QK_K == 0);
    const int64_t nb = k / QK_K;

    uint32_t aux32[2];
    const uint8_t * aux8 = (const uint8_t *)aux32;

    for (int i = 0; i < nb; i++) {

        const float d = fp16_to_fp32(x[i].d);

        for (int ib32 = 0; ib32 < QK_K/32; ++ib32) {
            memcpy(aux32, x[i].qs + 4*ib32, 2*sizeof(uint32_t));
            const float db = d * (0.5f + (aux32[1] >> 28)) * 0.25f;
            for (int l = 0; l < 4; ++l) {
                const uint8_t * grid = (const uint8_t *)(iq2xxs_grid + aux8[l]);
                const uint8_t  signs = ksigns_iq2xs[(aux32[1] >> 7*l) & 127];
                for (int j = 0; j < 8; ++j) {
                    y[j] = db * grid[j] * (signs & kmask_iq2xs[j] ? -1.f : 1.f);
                }
                y += 8;
            }
        }
    }
}

static void print_bits(const float * y, int64_t n) {
    for (int64_t i = 0; i < n; i++) {
        uint32_t b;
        memcpy(&b, &y[i], sizeof(b));
        printf("%08x\n", b);
    }
}

int main(int argc, char ** argv) {
    if (argc != 3) { fprintf(stderr, "usage: %s (q8_0|iq2_xxs|fp16) file\n", argv[0]); return 2; }
    const char * mode = argv[1];
    FILE * f = fopen(argv[2], "rb");
    if (!f) { perror("fopen"); return 1; }
    fseek(f, 0, SEEK_END);
    long size = ftell(f);
    fseek(f, 0, SEEK_SET);
    uint8_t * buf = malloc(size ? size : 1);
    if (fread(buf, 1, size, f) != (size_t)size) { perror("fread"); return 1; }
    fclose(f);

    if (!strcmp(mode, "q8_0")) {
        assert(size % 34 == 0);
        float * y = malloc(size / 34 * 32 * sizeof(float));
        dequantize_row_q8_0((const block_q8_0 *)buf, y, size / 34 * 32);
        print_bits(y, size / 34 * 32);
        free(y);
    } else if (!strcmp(mode, "iq2_xxs")) {
        assert(size % 66 == 0);
        float * y = malloc(size / 66 * 256 * sizeof(float));
        dequantize_row_iq2_xxs((const block_iq2_xxs *)buf, y, size / 66 * 256);
        print_bits(y, size / 66 * 256);
        free(y);
    } else if (!strcmp(mode, "fp16")) {
        assert(size % 2 == 0);
        for (long i = 0; i < size / 2; i++) {
            uint16_t h;
            memcpy(&h, buf + 2*i, 2);
            float v = fp16_to_fp32(h);
            uint32_t b;
            memcpy(&b, &v, 4);
            printf("%08x\n", b);
        }
    } else {
        fprintf(stderr, "unknown mode %s\n", mode);
        return 2;
    }
    free(buf);
    return 0;
}
