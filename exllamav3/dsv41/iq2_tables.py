def grid_table() -> torch.Tensor:
    """[256, 8] float32."""
    b = torch.tensor(list(bytes.fromhex(GRID_HEX)), dtype=torch.uint8)
    codes = torch.stack([(b >> s) & 3 for s in (0, 2, 4, 6)], dim=-1).reshape(256, 8)
    return torch.tensor(GRID_MAP, dtype=torch.float32)[codes.long()]


def ksigns_table() -> torch.Tensor:
    i = torch.arange(128)
    par = torch.zeros(128, dtype=torch.long)
    for b in range(7):
        par ^= (i >> b) & 1
    return (i | (par << 7)).to(torch.uint8)
